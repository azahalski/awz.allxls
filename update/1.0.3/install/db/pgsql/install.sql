-- Установка таблиц модуля awz.allxls

CREATE TABLE awz_allxls_role (
    ID int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NAME varchar(250) NOT NULL,
    PRIMARY KEY (ID)
    );

CREATE TABLE awz_allxls_role_relation (
    ID int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ROLE_ID int NOT NULL DEFAULT 0,
    RELATION varchar(8) NOT NULL DEFAULT '',
    PRIMARY KEY (ID)
    );

CREATE TABLE awz_allxls_permission (
    ID int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ROLE_ID int NOT NULL DEFAULT 0,
    PERMISSION_ID varchar(32) NOT NULL DEFAULT '0',
    VALUE int NOT NULL DEFAULT 0,
    PRIMARY KEY (ID)
    );
CREATE INDEX awz_allxls_role_relation_role_id ON awz_allxls_role_relation (role_id);
CREATE INDEX awz_allxls_role_relation_relation ON awz_allxls_role_relation (relation);
CREATE INDEX awz_allxls_permission_role_id ON awz_allxls_permission (role_id);
CREATE INDEX awz_allxls_permission_permission_id ON awz_allxls_permission (permission_id);

CREATE TABLE b_awz_allxls_sections (
  ID serial NOT NULL,
  NAME varchar(255) NOT NULL,
  CODE varchar(50) DEFAULT NULL,
  SORT integer NOT NULL DEFAULT 100,
  DATE_UPDATE timestamp DEFAULT NULL,
  UPDATED_BY integer NOT NULL DEFAULT 0,
  PRIMARY KEY (ID)
);
CREATE INDEX IX_AWZ_ALLXLS_SECTIONS_CODE ON b_awz_allxls_sections (CODE);
CREATE INDEX IX_AWZ_ALLXLS_SECTIONS_SORT ON b_awz_allxls_sections (SORT);

CREATE TABLE b_awz_allxls_profiles (
  ID serial NOT NULL,
  ACTIVE char(1) NOT NULL DEFAULT 'Y',
  SECTION_ID integer NOT NULL DEFAULT 0,
  "DESC" varchar(255) DEFAULT NULL,
  SETTINGS text,
  SETTINGS_HASH varchar(32) DEFAULT NULL,
  RUN_COUNT integer NOT NULL DEFAULT 0,
  DATE_UPDATE timestamp DEFAULT NULL,
  UPDATED_BY integer NOT NULL DEFAULT 0,
  DATE_LAST_RUN timestamp DEFAULT NULL,
  DATE_LAST_END timestamp DEFAULT NULL,
  DATE_NEXT_RUN timestamp DEFAULT NULL,
  CRON_ACTIVE char(1) NOT NULL DEFAULT 'N',
  CRON_SCHEDULE varchar(50) DEFAULT NULL,
  CRON_HIT_TIME integer NOT NULL DEFAULT 0,
  CRON_PAUSE integer NOT NULL DEFAULT 0,
  CRON_FALLS integer NOT NULL DEFAULT 0,
  CRON_RUNNING char(1) NOT NULL DEFAULT 'N',
  CRON_START_TIME timestamp DEFAULT NULL,
  CRON_LAST_ERR varchar(255) DEFAULT NULL,
  PRIMARY KEY (ID)
);
CREATE INDEX IX_AWZ_ALLXLS_PROFILES_SECTION_ID ON b_awz_allxls_profiles (SECTION_ID);
CREATE INDEX IX_AWZ_ALLXLS_PROFILES_ACTIVE ON b_awz_allxls_profiles (ACTIVE);
CREATE INDEX IX_AWZ_ALLXLS_PROFILES_NEXT_RUN ON b_awz_allxls_profiles (DATE_NEXT_RUN);
CREATE INDEX IX_AWZ_ALLXLS_PROFILES_CRON ON b_awz_allxls_profiles (CRON_ACTIVE, DATE_NEXT_RUN);

CREATE TABLE b_awz_allxls_profiles_hashes (
  ID serial NOT NULL,
  PROFILE_ID integer NOT NULL,
  SETTINGS_HASH varchar(32) NOT NULL,
  ROW_HASH varchar(32) NOT NULL,
  ELEMENT_ID varchar(50) NOT NULL DEFAULT '',
  ENTITY_ID varchar(50) NOT NULL DEFAULT '',
  PRIMARY KEY (ID)
);
CREATE INDEX IX_AWZ_ALLXLS_HASHES_PROFILE ON b_awz_allxls_profiles_hashes (PROFILE_ID);
CREATE INDEX IX_AWZ_ALLXLS_HASHES_ROW ON b_awz_allxls_profiles_hashes (PROFILE_ID, SETTINGS_HASH, ROW_HASH);
CREATE INDEX IX_AWZ_ALLXLS_HASHES_ELEMENT ON b_awz_allxls_profiles_hashes (ENTITY_ID, ELEMENT_ID);
