-- Установка таблиц модуля awz.allxls

CREATE TABLE IF NOT EXISTS awz_allxls_role (
    ID INT(10) UNSIGNED NOT NULL AUTO_INCREMENT,
    NAME VARCHAR(250) NOT NULL,
    PRIMARY KEY (ID)
    );

CREATE TABLE IF NOT EXISTS awz_allxls_role_relation (
    ID INT(10) UNSIGNED NOT NULL AUTO_INCREMENT,
    ROLE_ID INT(10) UNSIGNED NOT NULL,
    RELATION VARCHAR(8) NOT NULL DEFAULT '',
    PRIMARY KEY (ID),
    INDEX ROLE_ID (ROLE_ID),
    INDEX RELATION (RELATION)
    );

CREATE TABLE IF NOT EXISTS awz_allxls_permission (
    ID INT(10) UNSIGNED NOT NULL AUTO_INCREMENT,
    ROLE_ID INT(10) UNSIGNED NOT NULL,
    PERMISSION_ID VARCHAR(32) NOT NULL DEFAULT '0',
    VALUE TINYINT(3) UNSIGNED NOT NULL DEFAULT '0',
    PRIMARY KEY (ID),
    INDEX ROLE_ID (ROLE_ID),
    INDEX PERMISSION_ID (PERMISSION_ID)
    );

CREATE TABLE IF NOT EXISTS `b_awz_allxls_sections` (
  `ID` int NOT NULL AUTO_INCREMENT,
  `NAME` varchar(255) NOT NULL,
  `CODE` varchar(50) DEFAULT NULL,
  `SORT` int NOT NULL DEFAULT '100',
  `DATE_UPDATE` datetime DEFAULT NULL,
  `UPDATED_BY` int NOT NULL DEFAULT '0',
  PRIMARY KEY (`ID`),
  KEY `IX_AWZ_ALLXLS_SECTIONS_CODE` (`CODE`),
  KEY `IX_AWZ_ALLXLS_SECTIONS_SORT` (`SORT`)
);

CREATE TABLE IF NOT EXISTS `b_awz_allxls_profiles` (
  `ID` int NOT NULL AUTO_INCREMENT,
  `NAME` varchar(255) NOT NULL,
  `DESC` varchar(255) NOT NULL,
  `ACTIVE` char(1) NOT NULL DEFAULT 'Y',
  `TYPE` varchar(10) NOT NULL DEFAULT 'import',
  `SECTION_ID` int NOT NULL DEFAULT '0',
  `SETTINGS` longtext,
  `SETTINGS_HASH` varchar(32) DEFAULT NULL,
  `RUN_COUNT` int NOT NULL DEFAULT '0',
  `DATE_UPDATE` datetime DEFAULT NULL,
  `UPDATED_BY` int NOT NULL DEFAULT '0',
  `DATE_LAST_RUN` datetime DEFAULT NULL,
  `DATE_LAST_END` datetime DEFAULT NULL,
  `DATE_NEXT_RUN` datetime DEFAULT NULL,
  `CRON_ACTIVE` char(1) NOT NULL DEFAULT 'N',
  `CRON_SCHEDULE` varchar(50) DEFAULT NULL,
  `CRON_HIT_TIME` int NOT NULL DEFAULT '0',
  `CRON_PAUSE` int NOT NULL DEFAULT '0',
  `CRON_FALLS` int NOT NULL DEFAULT '0',
  `CRON_RUNNING` char(1) NOT NULL DEFAULT 'N',
  `CRON_START_TIME` datetime DEFAULT NULL,
  `CRON_LAST_ERR` varchar(255) DEFAULT NULL,
  PRIMARY KEY (`ID`),
  KEY `IX_AWZ_ALLXLS_PROFILES_SECTION_ID` (`SECTION_ID`),
  KEY `IX_AWZ_ALLXLS_PROFILES_ACTIVE` (`ACTIVE`),
  KEY `IX_AWZ_ALLXLS_PROFILES_NEXT_RUN` (`DATE_NEXT_RUN`),
  KEY `IX_AWZ_ALLXLS_PROFILES_CRON` (`CRON_ACTIVE`, `DATE_NEXT_RUN`)
);

CREATE TABLE IF NOT EXISTS `b_awz_allxls_profiles_hashes` (
  `ID` int NOT NULL AUTO_INCREMENT,
  `PROFILE_ID` int NOT NULL,
  `SETTINGS_HASH` varchar(32) NOT NULL,
  `ROW_HASH` varchar(32) NOT NULL,
  `ELEMENT_ID` varchar(50) NOT NULL DEFAULT '',
  `ENTITY_ID` varchar(50) NOT NULL DEFAULT '',
  PRIMARY KEY (`ID`),
  KEY `IX_AWZ_ALLXLS_HASHES_PROFILE` (`PROFILE_ID`),
  UNIQUE KEY `UK_AWZ_ALLXLS_HASHES_ROW` (`PROFILE_ID`, `ROW_HASH`),
  KEY `IX_AWZ_ALLXLS_HASHES_ROW` (`PROFILE_ID`, `SETTINGS_HASH`, `ROW_HASH`),
  KEY `IX_AWZ_ALLXLS_HASHES_ELEMENT` (`ENTITY_ID`, `ELEMENT_ID`)
);
